#!/usr/bin/env python3
"""Turns translation JSON files ({key: text}, same keys as
lib/l10n/source_it.json) into the Dart tables lib/l10n/tr_<code>.dart.

Usage: python3 tool/l10n_to_dart.py path/to/en.json [path/to/es.json ...]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def dart(s: str) -> str:
    s = (s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
         .replace('\n', '\\n'))
    return f"'{s}'"


def main():
    source = json.load(open(os.path.join(ROOT, 'lib', 'l10n', 'source_it.json'),
                            encoding='utf-8'))
    for path in sys.argv[1:]:
        code = os.path.splitext(os.path.basename(path))[0]
        table = json.load(open(path, encoding='utf-8'))
        missing = set(source) - set(table)
        if missing:
            raise SystemExit(f'{code}: missing {sorted(missing)[:5]}...')
        name = 'tr' + code.capitalize()
        lines = [f'// Generated by tool/l10n_to_dart.py from the {code} '
                 'translation.', '// ignore_for_file: lines_longer_than_80_chars', '',
                 f'const {name} = <String, String>{{']
        for key in sorted(source):
            lines.append(f'  {dart(key)}: {dart(table[key])},')
        lines.append('};')
        out = os.path.join(ROOT, 'lib', 'l10n', f'tr_{code}.dart')
        open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
        print(code, len(table), '->', out)


if __name__ == '__main__':
    main()
